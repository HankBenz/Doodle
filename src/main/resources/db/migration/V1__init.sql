create table timeslots
(
    id       bigint generated by default as identity primary key,
    owner_id uuid                        not null,
    start    timestamp(6) with time zone not null,
    finish   timestamp(6) with time zone not null,
    status   varchar(255)                not null,
    constraint timeslot_status_check check (status in ('FREE', 'BUSY')),
    constraint timeslot_range_check check (start < finish)
);

create index ix_timeslot_owner_id on timeslots (owner_id);
create index ix_timeslot_start_finish on timeslots (start, finish);

create table meetings
(
    id          bigint generated by default as identity primary key,
    timeslot_id bigint unique references timeslots (id),
    title       varchar(255),
    description varchar(2000)
);

create table meeting_participant
(
    id             bigint generated by default as identity primary key,
    meeting_id     bigint references meetings (id),
    participant_id uuid
);